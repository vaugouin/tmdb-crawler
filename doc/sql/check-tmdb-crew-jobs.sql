-- open-credits (OPEN-CREDITS-002): where does the TMDb list of jobs live in MariaDB?
-- Read-only. 1) any table named after jobs or departments, 2) the distinct CREW_DEPARTMENT /
-- CREW_JOB pairs in the four TMDb credit tables, with their number of credit rows.

SELECT TABLE_NAME, TABLE_ROWS
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = DATABASE()
  AND (TABLE_NAME LIKE '%JOB%' OR TABLE_NAME LIKE '%DEPARTMENT%')
ORDER BY TABLE_NAME;

SELECT COUNT(*) AS DISTINCT_PAIRS, COUNT(DISTINCT CREW_JOB) AS DISTINCT_JOBS
FROM (
  SELECT CREW_DEPARTMENT, CREW_JOB FROM T_WC_TMDB_PERSON_MOVIE WHERE CREDIT_TYPE = 'crew'
  UNION SELECT CREW_DEPARTMENT, CREW_JOB FROM T_WC_TMDB_PERSON_SERIE WHERE CREDIT_TYPE = 'crew'
  UNION SELECT CREW_DEPARTMENT, CREW_JOB FROM T_WC_TMDB_PERSON_SEASON WHERE CREDIT_TYPE = 'crew'
  UNION SELECT CREW_DEPARTMENT, CREW_JOB FROM T_WC_TMDB_PERSON_EPISODE WHERE CREDIT_TYPE = 'crew'
) j;

SELECT CREW_DEPARTMENT, CREW_JOB, SUM(N) AS CREDIT_ROWS
FROM (
  SELECT CREW_DEPARTMENT, CREW_JOB, COUNT(*) AS N FROM T_WC_TMDB_PERSON_MOVIE WHERE CREDIT_TYPE = 'crew' GROUP BY CREW_DEPARTMENT, CREW_JOB
  UNION ALL SELECT CREW_DEPARTMENT, CREW_JOB, COUNT(*) FROM T_WC_TMDB_PERSON_SERIE WHERE CREDIT_TYPE = 'crew' GROUP BY CREW_DEPARTMENT, CREW_JOB
  UNION ALL SELECT CREW_DEPARTMENT, CREW_JOB, COUNT(*) FROM T_WC_TMDB_PERSON_SEASON WHERE CREDIT_TYPE = 'crew' GROUP BY CREW_DEPARTMENT, CREW_JOB
  UNION ALL SELECT CREW_DEPARTMENT, CREW_JOB, COUNT(*) FROM T_WC_TMDB_PERSON_EPISODE WHERE CREDIT_TYPE = 'crew' GROUP BY CREW_DEPARTMENT, CREW_JOB
) j
GROUP BY CREW_DEPARTMENT, CREW_JOB
ORDER BY CREW_DEPARTMENT, CREDIT_ROWS DESC;
